/** Zeichnet den Schriftzug mit der linken oberen Ecke bei (x, y). Liefert die Hoehe. */
export function drawCredoLogo(doc: PDFKit.PDFDocument, x: number, y: number, width: number, color: string): number {
  const scale = width / VIEW_BOX_WIDTH;
  doc.save();
  doc.translate(x, y).scale(scale).translate(OFFSET_X, OFFSET_Y);
  for (const d of PATHS) {
    doc.path(d).fill(color);
  }
  doc.restore();
  return VIEW_BOX_HEIGHT * scale;
}
